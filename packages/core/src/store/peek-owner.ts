// DB 를 <읽기 전용으로> 열어 각인만 본다. <데이터베이스 파일>은 한 바이트도 안 바뀐다.
//
// 🔴 "아무것도 쓰지 않는다" 라고 적었다가 실측에서 <틀린 것으로 판명>됐다 (2026-08-22).
//    라이브 재현: 남의 DB 를 향해 `index` 를 걸었더니 가드가 막았고 `.db` 는
//    백업본과 <바이트 동일>이었다. 그런데 옆에 `-shm`(32KB) 과 `-wal`(0B) 이 <생겼다> —
//    WAL 모드 DB 는 읽기 전용 연결도 그 두 개를 만든다.
//    ★즉 정확한 약속은 "파일을 안 만든다" 가 아니라 <"DB 내용을 안 바꾼다">다.
//     막으려던 것(`journal_mode` 전환 · `CREATE TABLE` · `ALTER TABLE`)은 그대로 막힌다.
//
// 🔴 왜 필요한가 (코덱스 13차·14차 P1, 두 라운드 연속 지적):
//    `vault-ownership.ts` 는 "통과 못 하면 데이터를 한 글자도 쓰지 않는다" 고 약속하는데,
//    소유를 물으려면 먼저 `store.initialize()` 로 DB 를 열어야 했고 그 한 번이
//    `journal_mode = WAL` · `CREATE TABLE IF NOT EXISTS` · `ALTER TABLE` 마이그레이션을
//    <남의 DB 에> 실행했다. 데이터는 안 건드리지만 파일은 이미 바뀐다.
//    ★"데이터를 안 쓴다" 로 약속을 좁혀 적어 두는 것으로 두 번 넘겼는데, 좁힌 약속도
//     지켜야 할 약속이라 세 번째에는 <경로를 만든다>.
//
// ⚠️ 이 줄의 <두 플래그 모두> 변이가 살아남는다. 시험이 약해서가 아니라 <차이가 없어서>다.
//    같은 결론에 두 번, 서로 다른 경로로 도달했으므로 각각의 실측을 남긴다.
//
// ⚠️ `readonly: true` — 살아남는다 (2026-08-22). 떼도 `.db` 바이트가 안 바뀐다.
//    판별을 <세 가지 방법으로> 시도했고 셋 다 구별하지 못했다:
//      ① 그냥 열고 각인만 읽기            → 두 경우 다 바이트 동일
//      ② 파일에 읽기전용 속성(`attrib +R`) → SQLite 는 <쓰기 시점>에야 검사한다. 둘 다 열린다
//      ③ 뜨거운 WAL 4.4MB 를 두고 열기     → 읽기만으로는 체크포인트가 안 돈다. 둘 다 동일
//    ★그래도 남긴다: 이것이 막는 것은 <지금의 동작>이 아니라 <나중에 누가 여기에 쓰기를
//     더하는 것>이다. 그때 이 플래그가 있으면 조용히 쓰는 대신 <그 자리에서 던진다>.
//     즉 변이가 살아남는 것이 정상인 부류다 — 미래의 실수에 거는 잠금이라 현재 동작에 없다.
//    🔴 그러니 "변이가 살아남았다 → 지워도 된다" 로 읽지 마라. 반대다.
//
// ⚠️ `fileMustExist: true` 는 <이중 잠금>이다. 처음 여기 "readonly 만으로는 부족하다 —
//    없는 파일을 만들어 버린다" 고 적었는데 <틀렸다>. 실측(better-sqlite3, 이 저장소의
//    설치본): `new Database(없는경로, { readonly: true })` 는 `SQLITE_CANTOPEN` 을 던지고
//    파일을 <만들지 않는다>. 즉 두 플래그는 여기서 같은 결과를 낸다.
//    ★어떻게 알았나: `fileMustExist` 를 제거하는 변이를 심었더니 <살아남았다>.
//     시험이 약해서가 아니라 <차이가 없어서>였다 — 그래서 시험을 늘리는 대신 주석을 고친다.
//     이 저장소가 반복해서 잡는 부류(주석이 구현과 어긋남)를 내가 새 파일에서 또 했다.
//    남겨 두는 이유: 의도를 명시한다. 라이브러리 기본값이 바뀌어도 이 줄은 안 바뀐다.

import Database from 'better-sqlite3';

/**
 * DB 파일에 적힌 볼트 각인을 <내용을 바꾸지 않고> 알아낸다.
 *
 * ⚠️ <열지 않는> 것이 아니다 — 읽기 전용으로 연다. 위 머리주석의 실측을 보라.
 *
 * @returns 각인 문자열 · 각인이 없으면 `''` · <물어볼 수 없으면> `undefined`.
 *
 * 🔴 세 값을 <구별해서> 돌려준다. 한때 없는 것과 못 읽은 것을 같은 값으로 뭉갤까
 *    했는데, 그러면 "각인이 없으니 새 DB 다 → 가져가도 된다" 는 판단이 <파일이 깨져
 *    못 읽은 경우>까지 덮는다. 모르면 모른다고 말해야 부르는 쪽이 조심할 수 있다.
 *
 * ⚠️ 이 함수는 <거부에만> 쓴다. `undefined` 를 승인 근거로 삼지 마라 —
 *    각인의 정본은 여전히 `store.getMeta(VAULT_OWNER_KEY)` 이고, 그것을 대체하지 않는다.
 */
export function peekVaultOwner(dbPath: string, key: string): string | undefined {
  let db: Database.Database | undefined;
  try {
    db = new Database(dbPath, { readonly: true, fileMustExist: true });
    const row = db.prepare('SELECT value FROM stellavault_meta WHERE key = ?').get(key) as
      { value: string } | undefined;
    // 표가 있는데 행이 없다 = <아직 각인 안 된 DB>. 빈 문자열로 그 사실을 말한다.
    return row?.value ?? '';
  } catch {
    // 파일 없음 · 표 없음(옛 DB) · 권한 · 손상 — 전부 <물어볼 수 없다>로 접는다.
    // 여기서 종류를 가르지 않는 이유: 어느 쪽이든 부르는 쪽의 행동이 같다(정상 경로로 간다).
    return undefined;
  } finally {
    try { db?.close(); } catch { /* 닫기 실패는 판정에 영향이 없다 */ }
  }
}
